def send_email(to_email, subject, html_body):
    smtp_email    = os.environ.get('SMTP_EMAIL') or get_setting('smtp_email')
    smtp_password = os.environ.get('SMTP_PASSWORD') or get_setting('smtp_password')
    smtp_host     = os.environ.get('SMTP_HOST') or get_setting('smtp_host')
    smtp_port     = int(os.environ.get('SMTP_PORT') or get_setting('smtp_port') or 587)
    if not smtp_password:
        print(f'[EMAIL] No SMTP password set. Would send to {to_email}: {subject}')
        return False
    try:
        msg = MIMEMultipart('alternative')
        msg['Subject'] = subject
        from email.utils import formataddr
        msg['From'] = formataddr(('IIT Delhi PET Credit Portal', smtp_email))
        msg['To']   = to_email
        msg.attach(MIMEText(html_body, 'html'))
        with smtplib.SMTP(smtp_host, smtp_port) as server:
            server.starttls()
            server.login(smtp_email, smtp_password)
            server.sendmail(smtp_email, to_email, msg.as_string())
        return True
    except Exception as e:
        print(f'[EMAIL ERROR] {e}')
        return False

def generate_otp(length=6):
    return ''.join(random.choices(string.digits, k=length))

def create_otp(email, purpose):
    otp = generate_otp()
    expires_at = datetime.now() + timedelta(minutes=10)
    conn = get_db()
    c = conn.cursor()
    c.execute('UPDATE otp_store SET used=1 WHERE email=%s AND purpose=%s', (email, purpose))
    c.execute('INSERT INTO otp_store (email, otp, purpose, expires_at) VALUES (%s,%s,%s,%s)',
              (email, otp, purpose, expires_at))
    conn.commit()
    conn.close()
    return otp

def verify_otp(email, otp, purpose):
    conn = get_db()
    c = conn.cursor()
    c.execute('''SELECT * FROM otp_store
        WHERE email=%s AND otp=%s AND purpose=%s AND used=0
        AND expires_at > NOW()
        ORDER BY id DESC LIMIT 1''', (email, otp, purpose))
    row = fetchone(c)
    if row:
        c.execute('UPDATE otp_store SET used=1 WHERE id=%s', (row['id'],))
        conn.commit()
    conn.close()
    return row is not None

def login_required(f):
    @wraps(f)
    def decorated(*args, **kwargs):
        if 'company_id' not in session:
            return redirect(url_for('login_page'))
        return f(*args, **kwargs)
    return decorated

