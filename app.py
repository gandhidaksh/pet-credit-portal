# --- Geospatial classifier (lat/lon -> collection category, F, E, evidence) ---
# Loaded lazily on first use — takes ~1s to read, done once per worker process.
# These are small, pre-simplified/pre-reprojected parquet files (committed to
# git, ~40MB total) generated by preprocess_geo_data.py from the original
# ~200MB raw government datasets. Render's 512MB Starter instance was getting
# OOM-killed reading the raw files directly (just deserializing the 150MB
# rivers file alone cost ~1.3GB of RAM) — see the memory notes at the top of
# GeoClassifier.__init__ in geo_classifier.py for the full story. Because the
# small files are committed to git, there's nothing to download at deploy
# time anymore; if one is missing, that's a real problem (bad clone/commit),
# not a normal first-run state, so this fails loudly instead of trying to
# fetch and reprocess the raw ~200MB datasets on a memory-constrained instance.
_geo_classifier = None
def get_classifier():
    global _geo_classifier
    if _geo_classifier is None:
        base_dir = os.path.dirname(os.path.abspath(__file__))
        rivers_path = os.path.join(base_dir, "Rivers+ Streams", "wris_rivers_simplified.parquet")
        if not os.path.exists(rivers_path):
            raise FileNotFoundError(
                "Missing Rivers+ Streams/wris_rivers_simplified.parquet (and likely the other "
                "4 pre-processed geo files). These must be committed to git — run "
                "`python preprocess_geo_data.py` locally (with the raw datasets present) and "
                "commit the *_simplified.parquet / esz_reprojected.parquet outputs."
            )
        from geo_classifier import GeoClassifier
        _geo_classifier = GeoClassifier(verbose=False)
    return _geo_classifier

