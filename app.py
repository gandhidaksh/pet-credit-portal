def fetchone(cursor):
    row = cursor.fetchone()
    if row is None:
        return None
    return {cursor.description[i][0]: row[i] for i in range(len(row))}

def fetchall(cursor):
    rows = cursor.fetchall()
    return [{cursor.description[i][0]: row[i] for i in range(len(row))} for row in rows]

